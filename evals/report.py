"""
Render a results file as `scorecard.md`.

The scorecard is committed, and it is the most persuasive file in the
repository: it is the difference between claiming the harness works and showing
what it scores. It is regenerated rather than hand-edited.

It carries a regression delta against the previously committed scorecard,
because the number that matters is rarely the absolute one -- 62% structural
means little on its own and a great deal when last week was 81%.
"""
import json
import os
import re
from typing import Any, Dict, List, Optional

HERE = os.path.dirname(os.path.abspath(__file__))
SCORECARD = os.path.join(HERE, "scorecard.md")
PREVIOUS = os.path.join(HERE, "results", "previous.json")


def _pct(value: Optional[float]) -> str:
    return "—" if value is None else f"{value:.0%}"


def _delta(now: Optional[float], before: Optional[float]) -> str:
    """A change worth reading, or nothing. Sub-point noise is not a regression
    and printing it as one trains people to ignore the column."""
    if now is None or before is None:
        return ""
    diff = now - before
    if abs(diff) < 0.01:
        return " (=)"
    return f" ({'+' if diff > 0 else ''}{diff:.0%})"


def _load_previous() -> Dict[str, Any]:
    if not os.path.isfile(PREVIOUS):
        return {}
    try:
        with open(PREVIOUS, "r", encoding="utf-8") as fh:
            return json.load(fh)
    except (OSError, ValueError):
        return {}


def _key(row: Dict[str, Any]) -> str:
    return f"{row['task_id']}::{row['model']}"


def _fold(rows: List[Dict[str, Any]]) -> Dict[str, Dict[str, Any]]:
    """
    Collapse repeats into one row per task+model.

    `pass@k` is the share of runs with no structural failure and no error --
    which is the honest reading of "did this work", and the one that exposes a
    task that succeeds two times in three.
    """
    import statistics

    folded: Dict[str, Dict[str, Any]] = {}
    for row in rows:
        folded.setdefault(_key(row), []).append(row)

    out = {}
    for key, group in folded.items():
        judged = [r["quality"] for r in group if r["quality"] is not None]
        passes = sum(1 for r in group
                     if not r["error"] and r["structural"] >= 1.0)
        out[key] = {
            "task_id": group[0]["task_id"],
            "model": group[0]["model"],
            "mode": group[0]["mode"],
            "runs": len(group),
            "passes": passes,
            "structural": statistics.fmean(r["structural"] for r in group),
            "quality": statistics.fmean(judged) if judged else None,
            "cost_usd": statistics.fmean(r["cost_usd"] for r in group),
            "p50_latency": statistics.median(r["duration_sec"] for r in group),
            "errors": sum(1 for r in group if r["error"]),
            "unjudged": group[0].get("quality_skipped", ""),
        }
    return out


def render(report: Dict[str, Any], previous: Optional[Dict[str, Any]] = None) -> str:
    previous = previous if previous is not None else _load_previous()
    now = _fold(report["rows"])
    before = _fold(previous.get("rows", [])) if previous else {}

    lines = [
        "# Eval scorecard",
        "",
        "Regenerated by `python -m evals.runner --suite all --replay`. "
        "Do not hand-edit.",
        "",
        "**structural** -- the `expect` block: step count, agents involved, "
        "artifacts produced, every step completed, budgets respected. "
        "Deterministic, no model involved.  ",
        "**quality** -- the rubric, scored per criterion by "
        "`evals/judge.py` against the artifact files, never the synthesised "
        "briefing.  ",
        "**pass@k** -- runs with no error and no structural failure, over runs "
        "attempted.",
        "",
        "| task | model | mode | structural | quality | cost | p50 latency | pass@k |",
        "|---|---|---|---|---|---|---|---|",
    ]

    for key in sorted(now):
        row = now[key]
        was = before.get(key, {})
        lines.append(
            f"| `{row['task_id']}` | {row['model']} | {row['mode']} "
            f"| {_pct(row['structural'])}{_delta(row['structural'], was.get('structural'))} "
            f"| {_pct(row['quality'])}{_delta(row['quality'], was.get('quality'))} "
            f"| ${row['cost_usd']:.4f} "
            f"| {row['p50_latency']:.1f}s "
            f"| {row['passes']}/{row['runs']} |"
        )

    lines += ["", "## Per model", "",
              "| model | tasks | runs | errors | structural | quality | total cost | p50 latency |",
              "|---|---|---|---|---|---|---|---|"]
    for summary in report.get("summary", []):
        lines.append(
            f"| {summary['model']} | {summary['tasks']} | {summary['runs']} "
            f"| {summary['errors']} | {_pct(summary['structural'])} "
            f"| {_pct(summary['quality'])} | ${summary['cost_usd']:.4f} "
            f"| {summary['p50_latency']:.1f}s |")

    changed = [
        (k, before[k], now[k]) for k in sorted(now)
        if k in before and _verdict(before[k]) != _verdict(now[k])
    ]
    lines += ["", "## Changed verdict since the last scorecard", ""]
    if not changed:
        lines.append("Nothing changed verdict." if before
                     else "No previous scorecard to compare against.")
    else:
        for key, was, is_now in changed:
            lines.append(
                f"- `{is_now['task_id']}` on {is_now['model']}: "
                f"**{_verdict(was)} → {_verdict(is_now)}** "
                f"(structural {_pct(was['structural'])} → {_pct(is_now['structural'])})")

    unjudged = sorted({r["unjudged"] for r in now.values() if r["unjudged"]})
    if unjudged:
        lines += ["", "## Why some rows are unjudged", ""]
        for reason in unjudged:
            lines.append(f"- {reason}")
        lines.append("")
        lines.append(
            "An unjudged row still carries its structural score, which is "
            "deterministic and needs no model. It is not a passing quality "
            "score and must never be read as one.")

    lines.append("")
    return "\n".join(lines)


def _verdict(row: Dict[str, Any]) -> str:
    if row.get("errors"):
        return "error"
    return "pass" if row.get("structural", 0) >= 1.0 else "fail"


def write_scorecard(report: Dict[str, Any]) -> str:
    """Render, write, and keep this run as the baseline for the next delta."""
    body = render(report)
    with open(SCORECARD, "w", encoding="utf-8") as fh:
        fh.write(body)
    os.makedirs(os.path.dirname(PREVIOUS), exist_ok=True)
    with open(PREVIOUS, "w", encoding="utf-8") as fh:
        json.dump(report, fh, indent=1, ensure_ascii=False)
    print(f"wrote {SCORECARD}")
    return SCORECARD


if __name__ == "__main__":
    import sys
    with open(sys.argv[1], "r", encoding="utf-8") as fh:
        write_scorecard(json.load(fh))
